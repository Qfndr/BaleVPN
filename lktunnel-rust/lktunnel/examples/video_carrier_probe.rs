//! Isolated H.264 SEI carrier experiment. Does not modify the production carrier.
//! Real SPS/PPS/IDR frames plus standards-framed SEI cross two local WebRTC PCs.
//! No provider signaling, Internet throughput claim, STUN/TURN or auth stores.
#[path = "support/video_rtp.rs"]
mod video_rtp;
#[path = "support/video_sei.rs"]
mod video_sei;
use bytes::Bytes;
use std::{
    sync::Arc,
    time::{Duration, Instant},
};
use tokio::sync::mpsc;
use webrtc::{
    api::{
        media_engine::{MediaEngine, MIME_TYPE_H264},
        APIBuilder,
    },
    dtls_transport::dtls_transport_state::RTCDtlsTransportState,
    media::Sample,
    peer_connection::{configuration::RTCConfiguration, RTCPeerConnection},
    rtp_transceiver::rtp_codec::RTCRtpCodecCapability,
    track::track_local::{track_local_static_sample::TrackLocalStaticSample, TrackLocal},
};
type Error = Box<dyn std::error::Error>;
// Generated by the installed BlueStacks FFmpeg/libopenh264 encoder from one
// synthetic 16x16 black frame, not from user media. See fixture provenance JSON.
const PICTURE: &[u8] = include_bytes!("support/fixtures/black16.h264");
async fn peer() -> Result<Arc<RTCPeerConnection>, Error> {
    let mut media = MediaEngine::default();
    media.register_default_codecs()?;
    Ok(Arc::new(
        APIBuilder::new()
            .with_media_engine(media)
            .build()
            .new_peer_connection(RTCConfiguration {
                ice_servers: vec![],
                ..Default::default()
            })
            .await?,
    ))
}
async fn negotiate(a: &RTCPeerConnection, b: &RTCPeerConnection) -> Result<(), Error> {
    let offer = a.create_offer(None).await?;
    let mut complete = a.gathering_complete_promise().await;
    a.set_local_description(offer).await?;
    complete.recv().await;
    let offer = a.local_description().await.ok_or("missing offer")?;
    if !offer.sdp.contains("a=fingerprint:sha-256") || !offer.sdp.contains("H264/90000") {
        return Err("missing DTLS-SRTP/H264 offer".into());
    }
    b.set_remote_description(offer).await?;
    let answer = b.create_answer(None).await?;
    let mut complete = b.gathering_complete_promise().await;
    b.set_local_description(answer).await?;
    complete.recv().await;
    a.set_remote_description(b.local_description().await.ok_or("missing answer")?)
        .await?;
    Ok(())
}
fn payload(sequence: u32) -> Vec<u8> {
    let length = match sequence % 4 {
        0 => 1,
        1 => 256,
        2 => 4096,
        _ => video_sei::MAX_PAYLOAD,
    };
    (0..length)
        .map(|i| ((i * 37 + sequence as usize * 13) % 256) as u8)
        .collect()
}
fn access_unit(data: &[u8]) -> Result<Bytes, Error> {
    let sei = video_sei::encode_nal(data).map_err(|_| "SEI encoding failed")?;
    // SPS/PPS must precede the supplemental information and associated IDR.
    let idr = PICTURE
        .windows(5)
        .position(|w| w == [0, 0, 0, 1, 0x65])
        .ok_or("fixture IDR missing")?;
    let mut au = Vec::with_capacity(PICTURE.len() + sei.len() + 4);
    au.extend_from_slice(&PICTURE[..idr]);
    au.extend_from_slice(&[0, 0, 0, 1]);
    au.extend(sei);
    au.extend_from_slice(&PICTURE[idr..]);
    Ok(Bytes::from(au))
}
async fn probe(a: &RTCPeerConnection, b: &RTCPeerConnection) -> Result<serde_json::Value, Error> {
    let (tx, mut rx) = mpsc::channel(256);
    let mut tracks = Vec::new();
    for (side, pc) in [a, b].into_iter().enumerate() {
        let tx = tx.clone();
        pc.on_track(Box::new(move |track, _, _| {
            let tx = tx.clone();
            tokio::spawn(async move {
                let mut au = video_rtp::AccessUnit::default();
                while let Ok((packet, _)) = track.read_rtp().await {
                    let completed = au.push(
                        packet.header.sequence_number,
                        packet.header.timestamp,
                        packet.header.marker,
                        &packet.payload,
                    );
                    match completed {
                        Ok(Some(nals)) => {
                            let mut found = None;
                            let mut picture = false;
                            let mut reconstructed = Vec::new();
                            for nal in nals {
                                reconstructed.extend_from_slice(&[0, 0, 0, 1]);
                                reconstructed.extend_from_slice(&nal);
                                picture |= nal.first().is_some_and(|header| header & 31 == 5);
                                if nal.first().is_some_and(|header| header & 31 == 6) {
                                    match video_sei::decode_nal(&nal) {
                                        Ok(Some(value)) if found.is_none() => found = Some(value),
                                        Ok(None) => {}
                                        _ => return,
                                    }
                                }
                            }
                            if picture {
                                if let Some(data) = found {
                                    if tx.send((side, data, reconstructed)).await.is_err() {
                                        break;
                                    }
                                }
                            }
                        }
                        Ok(None) => {}
                        Err(_) => return,
                    }
                }
            });
            Box::pin(async {})
        }));
        let track = Arc::new(TrackLocalStaticSample::new(
            RTCRtpCodecCapability {
                mime_type: MIME_TYPE_H264.to_owned(),
                clock_rate: 90000,
                sdp_fmtp_line:
                    "level-asymmetry-allowed=1;packetization-mode=1;profile-level-id=42e01f".into(),
                ..Default::default()
            },
            "synthetic-video".into(),
            "isolated-local-probe".into(),
        ));
        let sender = pc
            .add_track(track.clone() as Arc<dyn TrackLocal + Send + Sync>)
            .await?;
        tokio::spawn(async move {
            let mut buffer = [0; 1500];
            while sender.read(&mut buffer).await.is_ok() {}
        });
        tracks.push(track);
    }
    negotiate(a, b).await?;
    tokio::time::timeout(Duration::from_secs(10), async {
        while a.dtls_transport().state() != RTCDtlsTransportState::Connected
            || b.dtls_transport().state() != RTCDtlsTransportState::Connected
        {
            tokio::time::sleep(Duration::from_millis(10)).await;
        }
    })
    .await?;
    let start = Instant::now();
    let mut received = [0usize; 2];
    for sequence in 0..24 {
        let expected = payload(sequence);
        let data = access_unit(&expected)?;
        for track in &tracks {
            track
                .write_sample(&Sample {
                    data: data.clone(),
                    duration: Duration::from_millis(33),
                    ..Default::default()
                })
                .await?;
        }
        let mut seen = [false; 2];
        for _ in 0..2 {
            let (side, data, reconstructed) =
                tokio::time::timeout(Duration::from_secs(2), rx.recv())
                    .await?
                    .ok_or("video receiver stopped")?;
            if seen[side] || data != expected {
                return Err("video payload integrity/order failure".into());
            }
            if reconstructed != access_unit(&expected)? {
                return Err("video access unit changed across RTP".into());
            }
            // The independent decoder receives actual reassembled RTP output,
            // including a fragmented 16 KiB SEI, rather than the sender buffer.
            if sequence == 3 && side == 0 {
                if let Some(path) = std::env::var_os("VIDEO_PROBE_DECODE_SAMPLE") {
                    std::fs::write(path, &reconstructed)?;
                }
            }
            seen[side] = true;
            received[side] += data.len();
        }
    }
    Ok(
        serde_json::json!({"ok":true,"localOnly":true,"productionCarrierModified":false,
        "carrier":"H264 SPS/PPS/IDR plus user_data_unregistered SEI over WebRTC RTP/DTLS-SRTP",
        "accessUnitsEachDirection":24,"payloadBytesEachDirection":received,
        "elapsedMs":start.elapsed().as_millis(),"providerVerified":false,"independentDecoderRunByThisProcess":false,
        "internetThroughputBenchmark":false,"externalIceServers":0}),
    )
}
#[tokio::main]
async fn main() -> Result<(), Error> {
    let a = peer().await?;
    let b = peer().await?;
    let result = tokio::time::timeout(Duration::from_secs(25), probe(&a, &b)).await;
    let _ = a.close().await;
    let _ = b.close().await;
    println!("{}", serde_json::to_string_pretty(&result??)?);
    Ok(())
}
